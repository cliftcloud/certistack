// planSchemaAdmissionLimits are the admission limits a plan must give, by their
// canonical name (admissionSettings lists where each may be written). The loader
// refuses a plan without one of them: a limit left out is 0, and 0 admits no run.
var planSchemaAdmissionLimits = []string{
	"max_host_ram_percent", "max_host_iowait_percent", "defer_retry_interval_sec", "max_defer_retries",
}

// admissionLimitRules say that each required admission limit is given in some
// spelling the loader reads: under admission_control or under the older
// admission block, and for the I/O wait limit under either of its two names.
// They are stated at the top of the plan, and not as the block's own required
// keys, because the loader reads the two blocks as one (a limit may be in
// either), and a plan that splits them is valid.
func admissionLimitRules() []any {
	var rules []any
	for _, limit := range planSchemaAdmissionLimits {
		var setting *admissionSetting
		for index := range admissionSettings {
			if admissionSettings[index].canonical == limit {
				setting = &admissionSettings[index]
			}
		}
		if setting == nil {
			panic(fmt.Sprintf("config: planSchemaAdmissionLimits names %q, which admissionSettings does not have", limit))
		}
		var spellings []any
		for _, spelling := range setting.spellings {
			block, key := spelling[0], spelling[1]
			spellings = append(spellings, map[string]any{
				"required":   []string{block},
				"properties": map[string]any{block: map[string]any{"type": "object", "required": []string{key}, "properties": notNull(key)}},
			})
		}
		rules = append(rules, map[string]any{"anyOf": spellings})
	}
	return rules
}

// planSchemaOneOf are the sections in which one of several spellings of a key
// must be given.
var planSchemaOneOf = map[string][][]string{
	"Plan":    {{"admission_control", "admission"}},
	"Network": {{"ip_range", "subnet_cidr"}},
	"Tier":    {{"level", "tier"}},
	"VM":      {{"vmid", "target_vmid"}},
}

// schemaBuilder turns the plan's Go types into schema objects.
type schemaBuilder struct {
	defs map[string]any
	// optionalDefs and strictDefs are the references ("#/$defs/Storage") held
	// by an optional key, and by a required key or a list item.
	optionalDefs, strictDefs map[string]bool
}

// object is the schema of a struct type: its keys as properties and nothing
// else (the loader refuses an unknown key).
func (b *schemaBuilder) object(t reflect.Type) map[string]any {
	properties := map[string]any{}
	var collect func(reflect.Type)
	collect = func(st reflect.Type) {
		for i := 0; i < st.NumField(); i++ {
			field := st.Field(i)
			if !field.IsExported() {
				continue
			}
			name, options, _ := strings.Cut(field.Tag.Get("yaml"), ",")
			if name == "-" {
				continue
			}
			if strings.Contains(options, "inline") {
				collect(field.Type)
				continue
			}
			if name == "" {
				name = strings.ToLower(field.Name)
			}
			properties[name] = b.property(t.Name(), name, field.Type)
		}
	}
	collect(t)
	required := map[string]bool{}
	for _, key := range planSchemaRequired[t.Name()] {
		required[key] = true
	}
	for name, property := range properties {
		schema := property.(map[string]any)
		if ref, isRef := schema["$ref"].(string); isRef {
			if required[name] {
				b.strictDefs[ref] = true
			} else {
				b.optionalDefs[ref] = true
			}
		}
		if !required[name] {
			properties[name] = nullable(schema)
		}
	}

	schema := map[string]any{"type": "object", "properties": properties, "additionalProperties": false}
	if required := planSchemaRequired[t.Name()]; len(required) > 0 {
		schema["required"] = required
	}
	var anyOf []any
	for _, alternatives := range planSchemaOneOf[t.Name()] {
		options := make([]any, len(alternatives))
		for index, key := range alternatives {
			options[index] = map[string]any{"required": []string{key}, "properties": notNull(key)}
		}
		anyOf = append(anyOf, map[string]any{"anyOf": options})
	}
	switch len(anyOf) {
	case 0:
	case 1:
		schema["anyOf"] = anyOf[0].(map[string]any)["anyOf"]
	default:
		schema["allOf"] = anyOf
	}
	switch t {
	case reflect.TypeOf(Probe{}):
		schema["allOf"] = probeTypeRules()
	case reflect.TypeOf(Plan{}):
		rules, _ := schema["allOf"].([]any)
		schema["allOf"] = append(rules, admissionLimitRules()...)
	}
	return schema
}

// property is the schema of one key.
func (b *schemaBuilder) property(owner, key string, t reflect.Type) map[string]any {
	schema := b.typeSchema(t)
	note, noted := planSchemaNotes[owner+"."+key]
	if !noted {
		return readsAnyScalar(schema, note)
	}
	if note.Description != "" {
		schema["description"] = note.Description
	}
	if note.Deprecated {
		schema["deprecated"] = true
	}
	if note.FoldedEnum != nil {
		schema["pattern"] = anyCasePattern(note.FoldedEnum, note.FoldedTrim, note.OrEmpty)
		schema["examples"] = note.FoldedEnum
	}
	if note.Trimmed {
		alternatives := make([]string, len(note.Enum))
		for index, value := range note.Enum {
			alternatives[index] = regexp.QuoteMeta(value.(string))
		}
		schema["pattern"] = enumPattern(alternatives, true, note.OrEmpty)
		schema["examples"] = note.Enum
	}
	if note.NotEnum != nil {
		schema["not"] = map[string]any{"enum": note.NotEnum}
	}
	if note.Enum != nil && !note.Trimmed {
		enum := note.Enum
		if note.OrEmpty {
			enum = append([]any{""}, enum...)
		}
		// On a list, the values are the items'.
		if schema["type"] == "array" {
			schema["items"].(map[string]any)["enum"] = enum
		} else {
			schema["enum"] = enum
		}
	}
	if note.Const != nil {
		schema["const"] = note.Const
	}
	if note.Default != nil {
		schema["default"] = note.Default
	}
	if note.Pattern != "" {
		schema["pattern"] = note.Pattern
	}
	if note.MinLength != nil {
		schema["minLength"] = *note.MinLength
	}
	if note.MaxLength != nil {
		schema["maxLength"] = *note.MaxLength
	}
	switch {
	case note.Min != nil && note.OrZero:
		schema["anyOf"] = []any{map[string]any{"const": 0}, map[string]any{"minimum": *note.Min}}
	case note.Min != nil:
		schema["minimum"] = *note.Min
	}
	if note.Max != nil {
		schema["maximum"] = *note.Max
	}
	if note.ExclusiveMin != nil {
		schema["exclusiveMinimum"] = *note.ExclusiveMin
	}
	if note.MinItems > 0 {
		schema["minItems"] = note.MinItems
	}
	if multiLine, isText := planTextKeys[owner+"."+key]; isText {
		schema["pattern"] = textPattern(multiLine)
	}
	if note.Const == false {
		// A boolean key that takes only false takes the loader's spellings of it.
		delete(schema, "const")
		schema["anyOf"] = []any{map[string]any{"const": false}, map[string]any{"enum": yamlBooleanSpellings(false)}}
	}
	return readsAnyScalar(schema, note)
}

// readsAnyScalar is schema for a text key the loader reads any scalar into:
// a number or a yes or no written unquoted is taken as its text (2026 is
// "2026"), which validate judges. A key with an enum takes only text: no
// number or yes or no is one of its values. Nor does a key with a pattern,
// which a schema cannot hold a number's text to (quotedTextKeys).
func readsAnyScalar(schema map[string]any, note fieldNote) map[string]any {
	if schema["type"] == "string" && note.Enum == nil && note.FoldedEnum == nil && note.Const == nil && !note.Trimmed && note.Pattern == "" {
		schema["type"] = []any{"string", "number", "boolean"}
	}
	return schema
}

// yamlBooleanSpellings are the words the loader reads into a boolean key as
// value, besides true and false: YAML 1.1's yes, no, on, off, y and n, in the
// letter cases the decoder takes, quoted or not.
func yamlBooleanSpellings(value bool) []any {
	if value {
		return texts("y", "Y", "yes", "Yes", "YES", "on", "On", "ON")
	}
	return texts("n", "N", "no", "No", "NO", "off", "Off", "OFF")
}

// nullable is schema that also accepts null: a key given no value, which the
// loader reads as the key left out. A section (a $ref) is made nullable in
// its definition, once every key that holds it is optional (PlanSchema).
func nullable(schema map[string]any) map[string]any {
	null := map[string]any{"type": "null"}
	if _, isRef := schema["$ref"]; isRef {
		return schema
	}
	switch kind := schema["type"].(type) {
	case string:
		schema["type"] = []any{kind, "null"}
	case []any:
		schema["type"] = append(kind, "null")
	}
	if enum, ok := schema["enum"].([]any); ok {
		schema["enum"] = append(enum, nil)
	}
	if constant, ok := schema["const"]; ok {
		delete(schema, "const")
		schema["enum"] = []any{constant, nil}
	}
	if options, ok := schema["anyOf"].([]any); ok && schema["type"] == nil {
		schema["anyOf"] = append(options, null)
	}
	return schema
}

// notNull is the rule that key, when given, has a value: a key given null is
// a key left out.
func notNull(keys ...string) map[string]any {
	properties := map[string]any{}
	for _, key := range keys {
		properties[key] = map[string]any{"not": map[string]any{"type": "null"}}
	}
	return properties
}

func (b *schemaBuilder) typeSchema(t reflect.Type) map[string]any {
	switch t.Kind() {
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"anyOf": []any{
			map[string]any{"type": "boolean"},
			map[string]any{"enum": append(yamlBooleanSpellings(true), yamlBooleanSpellings(false)...)},
		}}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice:
		items := b.typeSchema(t.Elem())
		if ref, isRef := items["$ref"].(string); isRef {
			b.strictDefs[ref] = true // a list item given null is no item the loader takes
		}
		return map[string]any{"type": "array", "items": items}
	case reflect.Pointer:
		return b.typeSchema(t.Elem())
	case reflect.Struct:
		if _, defined := b.defs[t.Name()]; !defined {
			b.defs[t.Name()] = nil // a placeholder, so a type that contains itself would not recurse
			b.defs[t.Name()] = b.object(t)
		}
		return map[string]any{"$ref": "#/$defs/" + t.Name()}
	}
	panic(fmt.Sprintf("config: the plan schema has no rule for %s, a %s", t, t.Kind()))
}

// probeTypeRules say which keys each probe type reads and needs, from the same
// table the loader refuses a misplaced key with (probeFields).
func probeTypeRules() []any {
	aliasesOf := map[string][]string{}
	for alias, canonical := range probeTypeAliases {
		aliasesOf[canonical] = append(aliasesOf[canonical], alias)
	}
	var rules []any
	for _, probeType := range probeTypes {
		names := append([]string{probeType}, aliasesOf[probeType]...)
		sort.Strings(names[1:])
		// A key the type does not read may be left at its zero value (tls: false
		// is "not set"), and nothing else.
		refused := map[string]any{}
		for _, field := range probeFields {
			if !field.readBy(probeType) {
				// Its zero value, null, and for a boolean the spellings of false.
				left := []any{probeFieldZero(field.key), nil}
				if left[0] == false {
					left = append(left, yamlBooleanSpellings(false)...)
				}
				refused[field.key] = map[string]any{"enum": left}
			}
		}
		then := map[string]any{}
		if len(refused) > 0 {
			then["properties"] = refused
		}
		var required []string
		switch {
		case probeType == "http":
			required = []string{"expected_status"}
			then["properties"] = mergeSchemas(refused, map[string]any{"expected_status": map[string]any{"minimum": 200}})
		case IsWireProbe(probeType):
			required = []string{"target_ip", "port"}
		}
		if len(required) > 0 {
			then["required"] = required
			properties, _ := then["properties"].(map[string]any)
			for key, rule := range notNull(required...) {
				if existing, ok := properties[key].(map[string]any); ok {
					rule = mergeSchemas(existing, rule.(map[string]any))
				}
				properties = mergeSchemas(properties, map[string]any{key: rule})
			}
			then["properties"] = properties
		}
		if len(then) > 0 {
			rules = append(rules, map[string]any{
				"if":   map[string]any{"properties": map[string]any{"type": map[string]any{"enum": texts(names...)}}, "required": []string{"type"}},
				"then": then,
			})
		}
	}
	// A qga probe needs a command (qga_ping defaults to ping).
	rules = append(rules, map[string]any{
		"if":   map[string]any{"properties": map[string]any{"type": map[string]any{"const": "qga"}}, "required": []string{"type"}},
		"then": map[string]any{"required": []string{"command"}, "properties": notNull("command")},
	})
	return rules
}

// probeFieldZero is the zero value of a probe key, which the loader reads as
// "not set".
func probeFieldZero(key string) any {
	t := reflect.TypeOf(Probe{})
	for i := 0; i < t.NumField(); i++ {
		if name, _, _ := strings.Cut(t.Field(i).Tag.Get("yaml"), ","); name == key {
			return reflect.Zero(t.Field(i).Type).Interface()
		}
	}
	panic(fmt.Sprintf("config: probeFields names %q, which Probe does not have", key))
}

func mergeSchemas(maps ...map[string]any) map[string]any {
	merged := map[string]any{}
	for _, m := range maps {
		for key, value := range m {
			merged[key] = value
		}
	}
	return merged
}
