// PlanSchema is a JSON Schema (draft 2020-12) for the YAML a plan is written
// in, so an editor with a YAML language server can complete a plan's keys,
// offer the values the loader accepts, and flag a mistake as it is typed.
//
// The structure is derived from the Plan type by reflection, with the same
// rules the loader's own decoder applies (the yaml tag names the key, a key the
// type does not have is unknown, and the loader refuses it), so a key the
// loader accepts cannot be missing and a key it does not accept cannot be
// offered. What the Go types cannot say (descriptions, the values a key may
// take, its range, which keys a plan must give, which keys a probe type reads)
// is written below, next to the code that enforces it where there is one; the
// tests hold both to the loader: every example plan validates against the
// schema, every annotation names a key that exists, and the values and ranges
// the schema allows are the ones the loader allows.
//
// The schema describes the plan file. It says what a JSON Schema can say of
// each value the loader checks (ranges, lengths, patterns, the letter case an
// enum is read in, which keys a section needs), and it does not replace the
// loader: rules that look across keys (an address inside network.ip_range, a
// MAC used once, a snapshot of the VM's own backup group) are checked by
// `certistack validate`.
func PlanSchema() map[string]any {
	builder := &schemaBuilder{defs: map[string]any{}, optionalDefs: map[string]bool{}, strictDefs: map[string]bool{}}
	root := builder.object(reflect.TypeOf(Plan{}))
	// A section only optional keys hold may be given no value, which the
	// loader reads as the section left out.
	for ref := range builder.optionalDefs {
		if !builder.strictDefs[ref] {
			builder.defs[strings.TrimPrefix(ref, "#/$defs/")].(map[string]any)["type"] = []any{"object", "null"}
		}
	}
	root["$schema"] = "https://json-schema.org/draft/2020-12/schema"
	root["title"] = "CertiStack plan"
	root["description"] = "A CertiStack disaster recovery validation plan (version v1). Generated by `certistack schema`; `certistack validate` is the authority."
	root["$defs"] = builder.defs
	return root
}

// PlanSchemaJSON is PlanSchema as indented JSON with a final newline.
func PlanSchemaJSON() []byte {
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(PlanSchema()); err != nil {
		panic(fmt.Sprintf("config: the plan schema cannot be encoded: %v", err)) // only plain maps, slices and scalars are in it
	}
	return out.Bytes()
}

// fieldNote is what a plan key's Go type cannot say. Notes are keyed
// "Type.key", the Go type name and the key as the YAML names it.
type fieldNote struct {
	Description string
	Enum        []any
	// FoldedEnum are values the loader reads in any letter case ("Preserve" is
	// "preserve"), and, when FoldedTrim is set, with white space around them. The
	// schema states them as a pattern and offers the canonical spellings as
	// examples, which is what an editor completes from.
	FoldedEnum []any
	FoldedTrim bool
	// OrEmpty accepts an empty value too (with FoldedTrim or Trimmed, white space
	// alone): the loader reads it as the key left out, and takes the default.
	OrEmpty bool
	// Trimmed says the loader trims white space from the value before it
	// compares it with Enum; the schema then states the enum as a pattern.
	Trimmed  bool
	Pattern  string
	Min, Max *float64
	// OrZero accepts 0 as well as the values from Min up: the loader reads a 0 as
	// "not set", and Min is the bound of a value that is set.
	OrZero       bool
	ExclusiveMin *float64
	MinLength    *int
	MaxLength    *int
	// NotEnum are values the pattern lets through and the loader refuses.
	NotEnum  []any
	MinItems int
	Const    any
	Default  any
	// Deprecated marks an older spelling that is still accepted, and a key the
	// loader accepts only with its zero value.
	Deprecated bool
}

func number(value float64) *float64 { return &value }
func length(value int) *int         { return &value }

func texts(values ...string) []any {
	enum := make([]any, len(values))
	for index, value := range values {
		enum[index] = value
	}
	return enum
}

// anyCasePattern is the regular expression of values the loader reads in any
// letter case: each letter is a class of its two cases ("[eE][pP]..."), because
// a JSON Schema pattern is an ECMA-262 expression with no flags. With trim the
// value may also have white space around it, as the loader trims it first.
func anyCasePattern(values []any, trim, orEmpty bool) string {
	alternatives := make([]string, len(values))
	for index, value := range values {
		var alternative strings.Builder
		for _, letter := range value.(string) {
			lower, upper := unicode.ToLower(letter), unicode.ToUpper(letter)
			if lower != upper {
				fmt.Fprintf(&alternative, "[%c%c]", lower, upper)
			} else {
				alternative.WriteRune(letter) // a digit, '-' or '_', none of which is special outside a class
			}
		}
		alternatives[index] = alternative.String()
	}
	return enumPattern(alternatives, trim, orEmpty)
}

// enumPattern is the pattern of one of alternatives (regular expressions),
// with white space around it when trim is set, or of an empty value when
// orEmpty is.
func enumPattern(alternatives []string, trim, orEmpty bool) string {
	space, optional := "", ""
	if trim {
		space = `\s*`
	}
	if orEmpty {
		optional = "?"
	}
	return "^" + space + "(?:" + strings.Join(alternatives, "|") + ")" + optional + space + "$"
}

// macAddressPattern is the spellings of a MAC address the loader accepts that a
// pattern can tell apart: six octets in colon, hyphen or dotted form (the three
// spellings net.ParseMAC reads), either letter case, the first octet even
// (a unicast address; every multicast and broadcast address has the lowest bit
// of its first octet set), or no address at all. The all-zero address has an
// even first octet and is refused by the note's NotEnum.
func macAddressPattern() string {
	const (
		pair    = `[0-9A-Fa-f]{2}`
		quad    = `[0-9A-Fa-f]{4}`
		unicast = `[0-9A-Fa-f][02468ACEace]`
	)
	return "^(?:" +
		unicast + "(?::" + pair + "){5}|" +
		unicast + "(?:-" + pair + "){5}|" +
		unicast + pair + `(?:\.` + quad + "){2})?$"
}

// zeroMACAddresses are the three spellings of the all-zero address.
func zeroMACAddresses() []any {
	return texts("00:00:00:00:00:00", "00-00-00-00-00-00", "0000.0000.0000")
}

// storageIDPattern is a PVE storage ID, as the loader's own expression spells
// it, or no storage at all (the key left empty is the key left out).
func storageIDPattern() string {
	rule := strings.TrimSuffix(strings.TrimPrefix(pveStorageIDRegex.String(), "^"), "$")
	return "^(?:" + rule + ")?$"
}

// machineSchemaPattern is the machine settings the loader may accept that a
// pattern can tell from the rest: a machine type of PVE's, with or without
// "type=", and anything after it, or a setting that starts with an option. The
// loader judges the options themselves, so the schema is never stricter than it.
func machineSchemaPattern() string {
	rule := strings.TrimSuffix(strings.TrimPrefix(pveMachineType.String(), "^"), "$")
	return "^(?:(?:type=)?" + rule + "(?:,.*)?|[A-Za-z][A-Za-z0-9-]*=.*)?$"
}

// frameworkNames are the compliance labels the loader accepts.
func frameworkNames() []any {
	names := make([]string, 0, len(validFrameworks))
	for name := range validFrameworks {
		names = append(names, name)
	}
	sort.Strings(names)
	return texts(names...)
}

// probeTypeNames are the probe types and their aliases, the types first.
func probeTypeNames() []any {
	names := append([]string(nil), probeTypes...)
	var aliases []string
	for alias := range probeTypeAliases {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	return texts(append(names, aliases...)...)
}

