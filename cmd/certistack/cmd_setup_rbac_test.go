// --part prints one part as a complete script for its host, so that
// `certistack setup rbac ... --part pve | ssh root@NODE sh -s` works (hardening
// F5, CR1-05).
func TestSetupRBACPartPrintsOneCompleteScript(t *testing.T) {
	args := []string{"setup", "rbac", "--node", "pve-node-01", "--overlay-storage", "certistack-scratch", "--pbs-datastore", "datastore1"}
	pve, err := runRootWithInput(t, "", append(args, "--part", "pve")...)
	if err != nil {
		t.Fatalf("--part pve: %v", err)
	}
	assertGolden(t, "setup_rbac_part_pve.golden", pve)
	pbs, err := runRootWithInput(t, "", append(args, "--part", "pbs")...)
	if err != nil {
		t.Fatalf("--part pbs: %v", err)
	}
	assertGolden(t, "setup_rbac_part_pbs.golden", pbs)

	if strings.Contains(pve, "proxmox-backup-manager user") || strings.Contains(pve, "PART 2 of 2: Proxmox Backup") {
		t.Errorf("--part pve carries the PBS part:\n%s", pve)
	}
	if strings.Contains(pbs, "pveum role") || strings.Contains(pbs, "PART 1 of 2: Proxmox VE") {
		t.Errorf("--part pbs carries the PVE part:\n%s", pbs)
	}
	for name, script := range map[string]string{"pve": pve, "pbs": pbs} {
		for _, want := range []string{"\nset -eu\n", "\nSTEP='", "\ntrap '"} {
			if !strings.Contains(script, want) {
				t.Errorf("--part %s is not a complete script: it lacks %q", name, strings.TrimSpace(want))
			}
		}
	}
	// Without the flag the output is what it always was, in one piece.
	both, err := runRootWithInput(t, "", args...)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(both, "PART 1 of 2") || !strings.Contains(both, "PART 2 of 2") {
		t.Errorf("the default output no longer holds both parts:\n%s", both)
	}
}

// Anything but pve or pbs is a usage error (exit 2) that prints no script.
func TestSetupRBACPartRefusesOtherValues(t *testing.T) {
	base := []string{"setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch"}
	for _, test := range []struct {
		extra []string
		want  string
	}{
		{[]string{"--part", "PVE"}, "invalid --part"},
		{[]string{"--part", "1"}, "invalid --part"},
		{[]string{"--part", "both"}, "invalid --part"},
		{[]string{"--part", "pve;id"}, "invalid --part"},
		{[]string{"--part", "pve", "--pbs-datastore", "datastore1", "--part", "pbs;id"}, "invalid --part"},
		{[]string{"--part", "pbs"}, "--part pbs needs --pbs-datastore"},
	} {
		out, err := runRootWithInput(t, "", append(append([]string(nil), base...), test.extra...)...)
		if err == nil || !strings.Contains(err.Error(), test.want) {
			t.Errorf("%v: error = %v, want one naming %q", test.extra, err, test.want)
			continue
		}
		if code := exitCodeForError(err); code != 2 {
			t.Errorf("%v: exit code %d, want 2", test.extra, code)
		}
		if out != "" {
			t.Errorf("%v printed a script anyway:\n%s", test.extra, out)
		}
	}
}

func TestSetupRBACZoneFlagIsOneZone(t *testing.T) {
	out, err := runRootWithInput(t, "", "setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", "--zone", "csSb01")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, "pveum acl modify /sdn/zones/csSb01 ") || strings.Contains(out, "pveum acl modify /sdn ") || strings.Contains(out, "pveum acl modify /sdn/zones ") {
		t.Errorf("--zone did not replace the ephemeral SDN paths:\n%s", out)
	}
	if !strings.Contains(out, "# Generated by: certistack setup rbac --node pve1 --overlay-storage scratch --zone csSb01\n") {
		t.Errorf("the header does not quote the command:\n%s", out)
	}
}

func TestSetupRBACRefusesBadOrConflictingFlags(t *testing.T) {
	for _, args := range [][]string{
		{"setup", "rbac"},
		{"setup", "rbac", "--node", "pve1"},
		{"setup", "rbac", "--overlay-storage", "scratch"},
		{"setup", "rbac", "--node", "pve1; reboot", "--overlay-storage", "scratch"},
		{"setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", "--zone", "a", "--sandbox-zones", "b"},
		{"setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", "--sandbox-zones", "a,,b"},
		{"setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", "--pbs-namespace", "prod"},
		{"setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", "extra"},
	} {
		out, err := runRootWithInput(t, "", args...)
		if err == nil {
			t.Errorf("%v was accepted", args)
		}
		if out != "" {
			t.Errorf("%v printed a script anyway:\n%s", args, out)
		}
	}
}

// Every flag refuses the shell metacharacters through the real command line
// too, and nothing is printed (no half-script a newcomer could still run).
func TestSetupRBACRefusesShellMetacharactersOnEveryFlag(t *testing.T) {
	base := map[string]string{"--node": "pve1", "--overlay-storage": "scratch"}
	flags := []string{"--node", "--overlay-storage", "--zone", "--sandbox-zones", "--pbs-datastore", "--pbs-namespace"}
	injections := []string{";INJECTED", "$(INJECTED)", "`INJECTED`", "\nINJECTED", "'", `"`, "&&INJECTED", "|INJECTED", ">INJECTED", " INJECTED"}
	for _, flag := range flags {
		for _, injection := range injections {
			if flag == "--sandbox-zones" && strings.Contains(injection, "\n") {
				// pflag reads this list as one line of CSV and drops what follows
				// a newline: the command is accepted, but nothing of the dropped
				// text may reach the script.
				out, _ := runRootWithInput(t, "", "setup", "rbac", "--node", "pve1", "--overlay-storage", "scratch", flag, "csSb01"+injection)
				if strings.Contains(out, "INJECTED") {
					t.Errorf("a newline in %s carried text into the script:\n%s", flag, out)
				}
				continue
			}
			args := []string{"setup", "rbac"}
			for name, value := range base {
				if name != flag {
					args = append(args, name, value)
				}
			}
			switch flag {
			case "--zone", "--sandbox-zones":
				args = append(args, flag, "csSb01"+injection)
			case "--pbs-namespace":
				args = append(args, "--pbs-datastore", "datastore1", flag, "prod"+injection)
			case "--pbs-datastore":
				args = append(args, flag, "datastore1"+injection)
			default:
				args = append(args, flag, base[flag]+injection)
			}
			out, err := runRootWithInput(t, "", args...)
			if err == nil {
				t.Errorf("%v was accepted", args)
			}
			if out != "" {
				t.Errorf("%v printed a script anyway:\n%s", args, out)
			}
		}
	}
}

// The command prints and runs nothing: neither it nor the script generator
// imports a package that starts a process.
func TestSetupRBACNeverExecutesAnything(t *testing.T) {
	for _, file := range []string{"cmd_setup_rbac.go", "../../internal/nodesetup/rbac.go"} {
		source, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		for _, forbidden := range []string{`"os/exec"`, `"syscall"`, `internal/process"`} {
			if strings.Contains(string(source), forbidden) {
				t.Errorf("%s imports %s", file, forbidden)
			}
		}
	}
}

